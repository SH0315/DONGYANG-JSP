package javabean;

public class PersonBean {
	// 이름, 나이 속성 설정
	private String name;
	private int age;
	
	//메소드 생성
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public int getAge() {
		return age;
	}
	public void setAge(int age) {
		this.age = age;
	}
	
	
}
